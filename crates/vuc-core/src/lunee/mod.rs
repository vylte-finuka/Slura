use uefi::prelude::*;
use uefi::CStr16;
use std::core::panic::PanicInfo;

#[panic_handler]
fn panic(info: &PanicInfo) -> ! {
    if let Some(stdout) = unsafe { uefi::system::stdout() } {
        let _ = stdout.output_string(CStr16::from_u16_with_nul(&[0x005B, 0x004C, 0x0055, 0x004E, 0x0045, 0x0045, 0x005D, 0x0020, 0x0050, 0x0041, 0x004E, 0x0049, 0x0043, 0x003A, 0x0020, 0x0000]).unwrap());
    }
    loop {}
}

#[alloc_error_handler]
fn alloc_error(_: core::alloc::Layout) -> ! { loop {} }

#[entry]
fn efi_main(image_handle: Handle, mut system_table: SystemTable<Boot>) -> Status {
    let _ = uefi::helpers::init(&system_table);
    let stdout = system_table.stdout();
    stdout.clear().unwrap();

    stdout.output_string(CStr16::from_u16_with_nul(&[
        0x003D,0x003D,0x003D,0x0020,0x0053,0x006C,0x0075,0x0072,0x0061,0x0020,
        0x004C,0x0075,0x006E,0x00E9,0x0065,0x0020,0x004B,0x0065,0x0072,0x006E,
        0x0065,0x006C,0x0020,0x0076,0x0030,0x002E,0x0031,0x0020,0x002D,0x0020,
        0x0050,0x0072,0x006F,0x0064,0x0075,0x0063,0x0074,0x0069,0x006F,0x006E,
        0x0020,0x0042,0x006F,0x006F,0x0074,0x0058,0x002D,0x006C,0x0069,0x006B,
        0x0065,0x0020,0x003D,0x003D,0x003D,0x000D,0x000A,0x0000
    ]).unwrap()).unwrap();

    let mut runtime = KernelRuntime::new();

    if let Err(_) = runtime.boot_phase(&mut system_table, image_handle) {
        stdout.output_string(CStr16::from_u16_with_nul(&[0x005B,0x0045,0x0052,0x0052,0x004F,0x0052,0x005D,0x0020,0x0042,0x006F,0x006F,0x0074,0x0020,0x0066,0x0061,0x0069,0x006C,0x0065,0x0064,0x002E,0x0020,0x0052,0x0065,0x0063,0x006F,0x0076,0x0065,0x0072,0x0079,0x0020,0x006D,0x006F,0x0064,0x0065,0x002E,0x000D,0x000A,0x0000]).unwrap()).unwrap();
        loop {}
    }

    stdout.output_string(CStr16::from_u16_with_nul(&[0x004C,0x0075,0x006E,0x00E9,0x0065,0x0020,0x004B,0x0065,0x0072,0x006E,0x0065,0x006C,0x0020,0x0062,0x006F,0x006F,0x0074,0x0065,0x0064,0x0020,0x0073,0x0075,0x0063,0x0063,0x0065,0x0073,0x0073,0x0066,0x0075,0x006C,0x006C,0x0079,0x002E,0x000D,0x000A,0x0000]).unwrap()).unwrap();

    loop {
        system_table.boot_services().stall(1_000_000);
    }
}
